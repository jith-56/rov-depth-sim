"""Run every scenario with the compiled simulator, analyse the logs, write plots + results.md.

usage: python scripts/run_all.py <path-to-run_sim> [--out results]
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "python"))
import rov_analysis as ra  # noqa: E402

DESCRIPTIONS = {
    "nominal": "0 -> 5 m step with a 1.5 N downwelling current and noisy sensor",
    "sensor_dropout": "3 s sensor outage at t = 30 s (warning only, then recovery)",
    "sensor_loss": "7 s sensor outage at t = 30 s (crosses 5 s hard limit, blind ascent)",
    "low_battery": "starts at 24% charge: warning at 20%, surfacing at 10%",
    "depth_limit": "operator requests 12 m, beyond the 10 m limit",
}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("exe")
    ap.add_argument("--out", default=os.path.join(ROOT, "results"))
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)

    lines = ["# Simulation results", "", "Generated by `scripts/run_all.py`.", ""]
    for name, desc in DESCRIPTIONS.items():
        csv = os.path.join(args.out, f"{name}.csv")
        subprocess.run([args.exe, name, csv], check=True, stdout=subprocess.DEVNULL)
        df = ra.load_log(csv)
        png = os.path.join(args.out, f"{name}.png")
        ra.plot_run(df, f"{name}: {desc}", png)

        lines += [f"## {name}", "", desc, "", f"![{name}]({name}.png)", ""]
        if name == "nominal":
            m = ra.compute_step_metrics(df["time_s"], df["true_depth_m"], 5.0)
            lines += [
                "| metric | value |", "|---|---|",
                f"| overshoot | {m.overshoot_pct:.2f} % |",
                f"| rise time (10-90%) | {m.rise_time_s:.2f} s |",
                f"| settling time (2% band) | {m.settling_time_s:.2f} s |",
                f"| steady-state error | {m.steady_state_error_m:+.4f} m |",
                "",
            ]
        tr = ra.state_transitions(df)
        if tr:
            lines += ["| time | transition |", "|---|---|"]
            lines += [f"| {t:.1f} s | {a} -> {b} |" for t, a, b in tr]
            lines.append("")
        print(f"{name}: ok")

    with open(os.path.join(args.out, "results.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
